def get_all_characters():
    """Kombiniert alle Charaktergruppen zu einem Dictionary"""
    all_chars = {}
    all_chars.update(main_characters)
    all_chars.update(team_7)
    all_chars.update(rookie_9)
    all_chars.update(adults)
    all_chars.update(villains)
    return all_chars

def get_characters_by_group(group_name):
    """Gibt Charaktere einer bestimmten Gruppe zurück"""
    groups = {
        "main": main_characters,
        "team_7": team_7,
        "rookie_9": rookie_9,
        "adults": adults,
        "villains": villains
    }
    return groups.get(group_name, {})

def get_character_info(name):
    """Gibt infos zu einem spezifischen Charakter zurück"""
    all_chars = get_all_characters()
    return all_chars.get(name, None)

def get_characters_with_binding(min_binding=None, max_binding=None):
    """Findet Charaktere basierend auf Bindung zu Sukuna"""
    all_chars = get_all_characters()
    result = {}

    for name, data in all_chars.items():
        binding = data.get("bindung_sukuna", 0)

        if min_binding is not None and binding < min_binding:
            continue
        if max_binding is not None and binding > max_binding:
            continue

        result[name] = data

    return result

